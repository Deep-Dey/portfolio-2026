import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--headless=new'] })
const p = await b.newPage()
await p.setViewport({ width: 1440, height: 800 })
await p.goto('http://localhost:5175/work/', { waitUntil: 'networkidle0' })
await new Promise(r=>setTimeout(r,1800))
await p.evaluate(() => { document.querySelector('.wp__cta').scrollIntoView({inline:'center'}) })
await new Promise(r=>setTimeout(r,600))
const r = await p.evaluate(() => { const e = document.querySelector('.wp__cta-mail').getBoundingClientRect(); return {x:e.x,y:e.y} })
await p.mouse.move(r.x + 60, r.y + 15)
await new Promise(r=>setTimeout(r,800))
const c = await p.evaluate(() => { const e = document.querySelector('.wp__cta').getBoundingClientRect(); return {x:e.x,y:e.y,width:e.width,height:e.height} })
await p.screenshot({ path: '.shots/work-cta.png', clip: c })
await b.close()
